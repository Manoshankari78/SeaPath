def _with_display_names(ports: list[dict]) -> list[dict]:
    """Derive `display_name` and `country` so the dataset above stays terse
    and a contributor adding a port cannot forget to keep them in sync."""
    out = []
    for p in ports:
        record = dict(p)
        record.setdefault("country", "India")
        record["display_name"] = f"{p['name']} — {p['state']}"
        out.append(record)
    return out


